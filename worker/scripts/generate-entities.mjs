// Generates the D1 schema and the Worker's entity registry from the app's entity
// definitions in base44/entities/*.jsonc.
//
//   node worker/scripts/generate-entities.mjs
//
// Outputs:
//   worker/src/entities.generated.js  — table, fields and row-level rules per entity
//   worker/migrations/0001_init.sql   — CREATE TABLE / CREATE INDEX statements
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const entitiesDir = path.join(root, "base44/entities");

const snake = (name) => name.replace(/([A-Z])/g, "_$1").toLowerCase().replace(/^_/, "");

const sqlType = (spec) => {
  if (spec.type === "number") return "REAL";
  if (spec.type === "integer") return "INTEGER";
  if (spec.type === "boolean") return "INTEGER";
  return "TEXT";
};

// Auth columns the app owns for its own sign-in, kept beside the User fields.
const USER_AUTH_COLUMNS = [
  '"email" TEXT NOT NULL UNIQUE',
  '"full_name" TEXT',
  `"status" TEXT NOT NULL DEFAULT 'active'`,
  '"password_hash" TEXT',
  '"totp_secret" TEXT',
  '"totp_enabled" INTEGER NOT NULL DEFAULT 0',
  '"recovery_codes" TEXT',
];

const files = fs.readdirSync(entitiesDir).filter((file) => file.endsWith(".jsonc")).sort();
const registry = {};
const statements = [];

for (const file of files) {
  const raw = fs.readFileSync(path.join(entitiesDir, file), "utf8").replace(/^\s*\/\/.*$/gm, "");
  const entity = JSON.parse(raw);
  const name = entity.name;
  const table = name === "User" ? "users" : snake(name);

  const fields = {};
  for (const [key, spec] of Object.entries(entity.properties || {})) {
    fields[key] = { type: spec.type || "string" };
    if (spec.enum) fields[key].enum = spec.enum;
    if (spec.default !== undefined) fields[key].default = spec.default;
    if (spec.rls) fields[key].rls = spec.rls;
  }

  registry[name] = { table, fields, rls: entity.rls ?? null };

  const columns = [
    '  "id" TEXT PRIMARY KEY',
    '  "created_date" TEXT NOT NULL',
    '  "updated_date" TEXT NOT NULL',
    '  "created_by_id" TEXT',
    ...Object.entries(fields).map(([key, spec]) => `  "${key}" ${sqlType(spec)}`),
  ];
  if (name === "User") columns.push(...USER_AUTH_COLUMNS.map((column) => `  ${column}`));

  statements.push(`CREATE TABLE IF NOT EXISTS ${table} (\n${columns.join(",\n")}\n);`);

  const indexes = ["created_date"];
  for (const column of ["user_id", "status", "partner_id", "referrer_id"]) {
    if (fields[column]) indexes.push(column);
  }
  if (name === "User") indexes.push("email", "role", "kyc_status", "mobile_number");
  if (fields.loan_id) indexes.push("loan_id");
  for (const column of indexes) {
    statements.push(`CREATE INDEX IF NOT EXISTS idx_${table}_${column} ON ${table}("${column}");`);
  }
}

statements.push(`CREATE TABLE IF NOT EXISTS password_resets (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  used_at TEXT
);`);

const out = `// Generated by worker/scripts/generate-entities.mjs from base44/entities/*.jsonc — do not edit by hand.
export const entities = ${JSON.stringify(registry, null, 2)};
`;

fs.writeFileSync(path.join(here, "../src/entities.generated.js"), out);
fs.writeFileSync(path.join(here, "../migrations/0001_init.sql"), `${statements.join("\n\n")}\n`);

console.log(`Generated ${Object.keys(registry).length} entities and ${statements.length} SQL statements.`);
